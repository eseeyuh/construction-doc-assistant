"""The construction demo: the text of every synthetic document, and the
authored answers the offline demo replays for them.

Everything here is fictional: the project (Kestrel Yard Depot Extension),
the contractor, roles, dates and amounts. Every document says so on its
first line. None of it is guidance for real construction work.

Documents (``demo_data/construction``, generated by ``app.demo.generate``):

- Inspection Procedure IP-01, Revision A: 48 hours' notice of an inspection;
- Inspection Procedure IP-01, Revision B: supersedes Revision A, 72 hours';
- Site Safety Rules SSR-01: helmets and safety footwear are required;
- Commercial Terms CT-01: a fictional payment schedule.

PDF pages are explicit lines, never wrapped automatically. Each requirement
sentence is one line of its own, so it is one statement for the evidence
gate (a sentence ends at a line end unless the next line starts in lower
case).

``REQUIREMENTS`` are the authored answers (``construction.FixtureProvider``):
written by hand from the documents, not by a model. Each is the exact
sentence as printed, a short action, and the responsible role and notice
period or due date only where that sentence states them; ``None`` where it
does not. They pass through the same evidence gate as model output.
"""

from __future__ import annotations

from dataclasses import dataclass

from app.demo.northbridge_content import Line, PdfDoc

AUTHOR = "Demo Contractor Ltd (fictional)"
SYNTHETIC = "SYNTHETIC DEMO DOCUMENT - fictional project, not for construction use."
PROJECT = "Kestrel Yard Depot Extension (fictional)"


def _p(*lines: str | Line) -> tuple[Line, ...]:
    return tuple(line if isinstance(line, Line) else Line(line) for line in lines)


def _h(text: str) -> Line:
    return Line(text, "heading")


def _t(text: str) -> Line:
    return Line(text, "title")


# --- the requirement sentences, shared by the documents and the answers ------------------

NOTICE_REV_A = "The Contractor must give the Site Manager 48 hours' notice of each inspection."
NOTICE_REV_B = "The Contractor must give the Site Manager 72 hours' notice of each inspection."
COVER_UP = "Work that is to be inspected must not be covered until the inspection has taken place."
RECORDS = "The Site Manager must sign the inspection record on the day of the inspection."
PPE = "Safety helmets and safety footwear are required at all times in the work area."
HI_VIS = "High-visibility vests should be worn near moving plant."
VISITORS = "All visitors must sign in at the site office before entering the work area."
INDUCTION = "The Site Manager must brief each new operative on these rules before they start work."
APPLICATION_1 = "The Contractor must submit payment application 1 by 27 November 2026."
APPLICATION_2 = "The Contractor must submit payment application 2 by 29 January 2027."
PAY_PERIOD = (
    "The Employer must pay each certified amount within 14 days of the payment certificate."
)


def _inspection_procedure(revision: str, issued: str, notice: str, *extra: str | Line) -> PdfDoc:
    return PdfDoc(
        title=f"Inspection Procedure IP-01, Revision {revision}",
        pages=(
            _p(
                SYNTHETIC,
                "",
                _t(PROJECT),
                _t(f"Inspection Procedure IP-01, Revision {revision}"),
                issued,
                "",
                _h("1. Purpose"),
                "This procedure sets out how site inspections are requested and recorded.",
                "",
                _h("2. Inspection requests"),
                notice,
                "Requests are made on the site inspection form.",
                "",
                _h("3. Covering up work"),
                COVER_UP,
                "",
                _h("4. Records"),
                RECORDS,
                *extra,
            ),
        ),
    )


INSPECTION_PROCEDURE_REV_A = _inspection_procedure("A", "Issued 14 September 2026.", NOTICE_REV_A)
INSPECTION_PROCEDURE_REV_B = _inspection_procedure(
    "B",
    "Issued 20 October 2026. This revision supersedes Revision A.",
    NOTICE_REV_B,
    "",
    _h("Revision note"),
    "The notice period in section 2 changed from 48 hours to 72 hours.",
)

SITE_SAFETY_RULES = PdfDoc(
    title="Site Safety Rules SSR-01",
    pages=(
        _p(
            SYNTHETIC,
            "",
            _t(PROJECT),
            _t("Site Safety Rules SSR-01"),
            "Issued 14 September 2026.",
            "",
            _h("Personal protective equipment"),
            PPE,
            HI_VIS,
            "",
            _h("Site access"),
            VISITORS,
            INDUCTION,
        ),
    ),
)

COMMERCIAL_TERMS = PdfDoc(
    title="Commercial Terms CT-01",
    pages=(
        _p(
            SYNTHETIC,
            "",
            _t(PROJECT),
            _t("Commercial Terms CT-01"),
            "Issued 21 September 2026. All parties, amounts and dates are fictional.",
            "",
            _h("Payment schedule"),
            "Interim payment 1 of 120,000 GBP covers the substructure.",
            "Interim payment 2 of 180,000 GBP covers the steel frame.",
            APPLICATION_1,
            APPLICATION_2,
            PAY_PERIOD,
            "",
            _h("Retention"),
            "Retention of 3 percent applies to each interim payment.",
        ),
    ),
)

# Paths under demo_data/construction, as manifest.yaml lists them.
CONSTRUCTION_DOCUMENTS: dict[str, PdfDoc] = {
    "documents/IP-01_Inspection_Procedure_RevA.pdf": INSPECTION_PROCEDURE_REV_A,
    "documents/IP-01_Inspection_Procedure_RevB.pdf": INSPECTION_PROCEDURE_REV_B,
    "documents/SSR-01_Site_Safety_Rules.pdf": SITE_SAFETY_RULES,
    "documents/CT-01_Commercial_Terms.pdf": COMMERCIAL_TERMS,
}


# --- the authored answers -----------------------------------------------------------------


@dataclass(frozen=True, slots=True)
class AuthoredRequirement:
    """One requirement as the fixture states it. ``statement`` is the exact
    sentence; every other value is copied from it, or None when it does not
    state one. ``due_date`` only for a full calendar date in the sentence."""

    statement: str
    action: str
    responsible_role: str | None = None
    notice_period: str | None = None
    due_date: str | None = None  # YYYY-MM-DD


