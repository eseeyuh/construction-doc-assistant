def _control(reference: str, kind: str, issue: tuple[str, str], pages: int) -> tuple[Line, ...]:
    return _table(
        _FIELD,
        ("Field", "Detail"),
        ("Document reference", reference),
        ("Document type", kind),
        issue,
        ("Status", "Issued for use on this project (fictional)"),
        ("Organisation", AUTHOR),
        ("Number of pages", str(pages)),
    )


