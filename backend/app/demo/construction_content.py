_WRAP = 92  # characters per body line; the renderer refuses a line that does not fit


def _p(*items: str | Line | tuple[Line, ...]) -> tuple[Line, ...]:
    out: list[Line] = []
    for item in items:
        if isinstance(item, tuple):
            out.extend(item)
        else:
            out.append(item if isinstance(item, Line) else Line(item))
    return tuple(out)


def _h(text: str) -> Line:
    return Line(text, "heading")


def _t(text: str) -> Line:
    return Line(text, "title")


def _para(text: str) -> tuple[Line, ...]:
    """Descriptive prose, wrapped onto explicit lines."""
    return tuple(Line(line) for line in textwrap.wrap(text, _WRAP))


def _table(
    columns: tuple[float, ...], head: tuple[str, ...], *rows: tuple[str, ...]
) -> tuple[Line, ...]:
    return (
        Line("\t".join(head), "table-head", columns),
        *(Line("\t".join(row), "table-row", columns) for row in rows),
    )


