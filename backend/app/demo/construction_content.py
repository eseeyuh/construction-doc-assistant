"""The construction demo: the text of every synthetic document, and the
authored answers the offline demo replays for them.

Everything here is fictional: the project (Kestrel Yard Depot Extension),
the contractor, roles, dates and amounts. Every page of every document says so on its
first line. None of it is guidance for real construction work.

Documents (``demo_data/construction``, generated by ``app.demo.generate``):

- Inspection Procedure IP-01, Revision A: 48 hours' notice of an inspection;
- Inspection Procedure IP-01, Revision B: supersedes Revision A, 72 hours';
- Site Safety Rules SSR-01: helmets and safety footwear are required;
- Commercial Terms CT-01: a fictional payment schedule.

PDF pages are explicit lines: the descriptive prose is wrapped here, never
by the renderer. Each requirement sentence is one line of its own, so it is
one statement for the evidence gate (a sentence ends at a line end unless
the next line starts in lower case).

Around the requirements each document carries descriptive context: document
control, background, scope, definitions, informational tables and clearly
labelled illustrative examples, with a header and footer on every page. That
context states no duty, deadline, prohibition or payment condition and does
not restate a requirement, so the register below stays complete.

``REQUIREMENTS`` are the authored answers (``construction.FixtureProvider``):
written by hand from the documents, not by a model. Each is the exact
sentence as printed, a short action, and the responsible role and notice
period or due date only where that sentence states them; ``None`` where it
does not. They pass through the same evidence gate as model output.
"""

