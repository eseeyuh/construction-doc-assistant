    AuthoredRequirement(HI_VIS, "Wear a high-visibility vest near moving plant"),
    AuthoredRequirement(VISITORS, "Sign in at the site office before entering the work area",
                        responsible_role="visitors"),
    AuthoredRequirement(INDUCTION, "Brief each new operative on the site rules",
                        responsible_role="Site Manager"),
    AuthoredRequirement(APPLICATION_1, "Submit payment application 1",
                        responsible_role="Contractor", due_date="2026-11-27"),
    AuthoredRequirement(APPLICATION_2, "Submit payment application 2",
                        responsible_role="Contractor", due_date="2027-01-29"),
